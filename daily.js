function dailyQuote() {
  // 按天取固定一句，保证当天不变
  const dayIndex = Math.floor(Date.now() / 86400000);
  return QUOTES[dayIndex % QUOTES.length];
}
function renderQuote() {
  const el = $("#dbQuote");
  if (el) el.textContent = dailyQuote();
}

renderQuote();
